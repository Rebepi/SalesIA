import { afterEach, expect, it, vi } from "vitest";
import { cleanup, fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import { OperatingCalendarEditor } from "../src/features/organizacion/components/OperatingCalendarEditor";
import { apiClient } from "../src/api/client";
afterEach(() => { cleanup(); vi.restoreAllMocks(); });
const rules = { weekly: Object.fromEntries(["MON", "TUE", "WED", "THU", "FRI", "SAT", "SUN"].map(day => [day, day === "SUN" ? [] : [{ start: "08:00", end: "18:00" }]])), cutoff_time: "16:00", holidays: [{ day: "2026-12-25", name: "Navidad", annual: true }], special_days: [], payment_day_basis: "calendar", payment_roll: "next", payment_due_time: "18:00", delivery_roll: "next", reminder_roll: "next", enforce_delivery_hours: true };
const calendar = { branch_id: null, branch_name: "Empresa", timezone: "America/Lima", version: 1, company_version: 1, rules, overrides: {}, origins: {}, configured: true };
it("usa switches y horarios compactos y conserva los datos de guardado", async () => {
  const request = vi.spyOn(apiClient, "request").mockImplementation(async path => path === "/api/v1/branches" ? [] as never : String(path).endsWith("/calculate") ? { at: "2026-10-22T18:00:00Z", local_start: "2026-10-21T12:00", before_roll: "2026-10-22", days: 1, basis: "calendar", roll: "next", after_cutoff: false, calendar, day: { reason: "Jornada hábil" }, definition: "Cálculo de prueba" } as never : calendar as never);
  render(<OperatingCalendarEditor canWrite />);
  const yearly = await screen.findByRole("switch", { name: "Cada año" });
  expect(screen.queryByRole("checkbox")).toBeNull();
  fireEvent.click(yearly);
  const monday = screen.getByRole("region", { name: "Horario de Lunes" });
  fireEvent.change(within(monday).getByLabelText("Inicio del tramo 1"), { target: { value: "09:00" } });
  fireEvent.change(screen.getByRole("textbox", { name: "Motivo del cambio" }), { target: { value: "Nuevo horario documentado" } });
  fireEvent.click(screen.getByRole("button", { name: "Guardar calendario" }));
  await waitFor(() => expect(request.mock.calls.some(([, options]) => options?.method === "PUT")).toBe(true));
  const body = JSON.parse(String(request.mock.calls.find(([, options]) => options?.method === "PUT")?.[1]?.body));
  expect(body.overrides.holidays[0].annual).toBe(false);
  expect(body.overrides.weekly.MON[0].start).toBe("09:00");
  expect(body.expected_company_version).toBe(1);
});
it("respeta permisos y conserva el switch de corte en la simulación", async () => {
  const request = vi.spyOn(apiClient, "request").mockImplementation(async path => path === "/api/v1/branches" ? [] as never : String(path).endsWith("/calculate") ? { at: "2026-10-22T18:00:00Z", local_start: "2026-10-21T12:00", before_roll: "2026-10-22", days: 1, basis: "calendar", roll: "next", after_cutoff: false, calendar, day: { reason: "Jornada hábil" }, definition: "Cálculo de prueba" } as never : calendar as never);
  render(<OperatingCalendarEditor canWrite={false} />);
  const yearly = await screen.findByRole("switch", { name: "Cada año" });
  expect((yearly as HTMLInputElement).disabled).toBe(true);
  expect(screen.queryByRole("button", { name: "Guardar calendario" })).toBeNull();
  const cutoff = screen.getByRole("switch", { name: "Respetar corte" }) as HTMLInputElement;
  expect(cutoff.checked).toBe(true);
  fireEvent.click(cutoff);
  const form = cutoff.closest("form")!;
  fireEvent.change(within(form).getByLabelText("Instante inicial"), { target: { value: "2026-10-21T12:00" } });
  fireEvent.submit(form);
  await waitFor(() => expect(request.mock.calls.some(([path]) => String(path).endsWith("/calculate"))).toBe(true));
  const body = JSON.parse(String(request.mock.calls.find(([path]) => String(path).endsWith("/calculate"))?.[1]?.body));
  expect(body.respect_cutoff).toBe(false);
});
